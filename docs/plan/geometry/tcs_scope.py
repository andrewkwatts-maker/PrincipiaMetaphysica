"""Scope: published content blocks naming TCS without any qualifier in the same block."""
import json, re, sys, collections
# -I ignores PYTHONIOENCODING, and Windows consoles cannot print Omega otherwise.
sys.stdout.reconfigure(encoding="utf-8")
P = "H:/Projects/MathsPhysicsEcosystem/PrincipiaMetaphysica/AutoGenerated/"
Q = re.compile(r"retired|refused|off-path|false|superseded|withdrawn|exclu|not a |cannot|"
               r"no published|formerly|used to|abandon|legacy|historical|seed_24|seed 24|"
               r"relocated|demoted|was described|earlier|parity|kovalev|chnp|range|"
               r"reading|belonged|not taken from|no longer", re.I)
hits = collections.Counter(); ex = {}
def walk(o, path):
    if isinstance(o, dict):
        for k, v in o.items(): walk(v, path + [str(k)])
    elif isinstance(o, list):
        for i, v in enumerate(o): walk(v, path + [str(i)])
    elif isinstance(o, str) and "TCS" in o and not Q.search(o):
        key = "/".join(path[:3]); hits[key] += 1; ex.setdefault(key, re.sub("<[^>]+>", "", o)[:140])
for f in ("sections.json", "formulas.json", "parameters.json"):
    walk(json.load(open(P + f, encoding="utf-8")), [f])
print(len(hits), "containers,", sum(hits.values()), "strings")
for k, n in hits.most_common(60): print(n, k, "|", ex[k][:110])
