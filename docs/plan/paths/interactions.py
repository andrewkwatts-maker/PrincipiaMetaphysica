"""Which fork options can interact (Track S, 2026-10-26).

A single-deviation run changes a set of rows relative to `active`. Two options of
different forks can only produce a non-additive joint result on rows that both
change; if their sets are disjoint, the joint path is the two deltas combined.
So only overlapping option pairs need a joint build.

Usage: python -I interactions.py RUNS [OUT.json]
"""
import itertools, json, math, sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")


def rows(run):
    path = run / "AutoGenerated" / "parameters.json"
    if not path.is_file():
        return None
    data = json.loads(path.read_text(encoding="utf-8"))["parameters"]
    return {k: v.get("value") for k, v in data.items()}


def differs(a, b):
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        if math.isnan(a) and math.isnan(b):
            return False
        return not math.isclose(a, b, rel_tol=1e-12, abs_tol=0.0)
    return a != b


def changed(base, other):
    keys = set(base) | set(other)
    return {k for k in keys if differs(base.get(k), other.get(k))}


def deviations(runs):
    """{(fork, option): changed rows} for every finished single-deviation run."""
    base = rows(runs / "active")
    if base is None:
        raise SystemExit("no active baseline in %s" % runs)
    out = {}
    for run in sorted(runs.iterdir()):
        if "--" not in run.name or not (run / "DONE.json").is_file():
            continue
        other = rows(run)
        if other is not None:
            out[tuple(run.name.split("--", 1))] = changed(base, other)
    return out


def overlaps(devs):
    """Option pairs from different forks whose changed rows intersect."""
    hits = []
    for (a, sa), (b, sb) in itertools.combinations(sorted(devs.items()), 2):
        if a[0] != b[0] and sa & sb:
            hits.append({"a": "--".join(a), "b": "--".join(b),
                         "shared": len(sa & sb), "example": sorted(sa & sb)[:5]})
    return hits


def main(argv):
    runs = Path(argv[1])
    devs = deviations(runs)
    pairs = sum(1 for x, y in itertools.combinations(devs, 2) if x[0] != y[0])
    hits = overlaps(devs)
    report = {"options": len(devs), "inert": sum(1 for s in devs.values() if not s),
              "cross_fork_pairs": pairs, "overlapping_pairs": len(hits),
              "pairs": sorted(hits, key=lambda h: -h["shared"])}
    print("%d options (%d inert), %d cross-fork pairs, %d overlap"
          % (report["options"], report["inert"], pairs, len(hits)))
    if len(argv) > 2:
        Path(argv[2]).write_text(json.dumps(report, indent=1), encoding="utf-8")


if __name__ == "__main__":
    main(sys.argv)
