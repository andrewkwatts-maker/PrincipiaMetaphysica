#!/bin/sh
# Full site main, fresh fast main (gate), twin, then every computed deviation.
S="$1"; P='H:/Projects/MathsPhysicsEcosystem/PrincipiaMetaphysica'
stat() { python -c "import json;s=json.load(open('$1/AutoGenerated/statistics.json',encoding='utf-8'))['framework_statistics'];print(s['chi_squared'],s['degrees_of_freedom'])"; }
cd /c
python -m metaphysica.build --out "$P" --keep-going > "$S/main_build2.log" 2>&1; echo "site exit=$? stats=$(stat $P)"
rm -rf "$S/runs/active"; python -m metaphysica.build --out "$S/runs/active" --fast --keep-going > "$S/runs/active.log" 2>&1
echo "active stats=$(stat $S/runs/active)"
[ "$(stat $S/runs/active | cut -d' ' -f2)" = "$(stat $P | cut -d' ' -f2)" ] || { echo "GATE FAILED: fresh dof differs from site"; exit 3; }
rm -rf "$S/runs/active2"; python -m metaphysica.build --out "$S/runs/active2" --fast --keep-going > "$S/runs/active2.log" 2>&1; echo "active2 stats=$(stat $S/runs/active2)"
ids=$(cd "$S/runs" && for d in *--*; do [ -d "$d" ] && [ -f "$d/AutoGenerated/build_status.json" ] && python -c "import json,sys;sys.exit(0 if not any(s['id']=='run_all_simulations' for s in json.load(open('$d/AutoGenerated/build_status.json',encoding='utf-8'))['failed_steps']) else 1)" && echo "$d"; done)
echo "rerunning $(echo $ids | wc -w) paths"
for i in $ids; do rm -f "$S/runs/$i/DONE.json"; done
python "$S/sweep.py" "$S/runs" $ids > "$S/runs/sweep6.out" 2>&1; tail -1 "$S/runs/sweep6.out"
python "$S/triage.py" "$S/runs" | grep -E '^\['
