"""Headless check of the Paths UI against a local static server. Prints one line per check."""
import subprocess, sys, time
from playwright.sync_api import sync_playwright

ROOT, PORT = sys.argv[1], 8765
SHOT = sys.argv[2]
BASE = "http://127.0.0.1:%d/Pages/" % PORT
PID = "flavour_seed_coupling--calibrated_24"


def check(label, ok, extra=""):
    print("%s %s %s" % ("PASS" if ok else "FAIL", label, extra))


def text(page, url):
    page.goto(url, wait_until="networkidle")
    page.wait_for_timeout(1500)
    return page.inner_text("body")


srv = subprocess.Popen([sys.executable, "-m", "http.server", str(PORT), "-d", ROOT],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(1.5)
try:
    with sync_playwright() as pw:
        br = pw.chromium.launch()
        page = br.new_page(viewport={"width": 1280, "height": 900})
        errs = []
        page.on("console", lambda m: errs.append(m.text) if m.type == "error" else None)
        page.on("pageerror", lambda e: errs.append(str(e)))
        t = text(page, BASE + "paths.html")
        check("paths page lists main and the path", "Main path" in t and "calibrated_24" in t)
        for view in ("switches", "lineage"):
            page.click('[data-view="%s"]' % view)
            page.wait_for_timeout(500)
            n = page.locator("#pp-svg *").count()
            check("view %s renders" % view, n > 20, "svg nodes=%d" % n)
        main_t = text(page, BASE + "parameters.html")
        check("main page: no path bar", page.locator(".pm-path-bar").count() == 0)
        path_t = text(page, BASE + "parameters.html?path=" + PID)
        check("path page: bar shown", page.locator(".pm-path-bar").count() == 1)
        check("path page: values differ from main", path_t != main_t,
              "y_e 0.3004 present=%s" % ("0.3004" in path_t or "0.300" in path_t))
        check("path page: no notice", "results unavailable" not in path_t)
        page.screenshot(path=SHOT, clip={"x": 0, "y": 0, "width": 1280, "height": 160})
        page.click(".pm-path-return")
        page.wait_for_load_state("networkidle")
        page.wait_for_timeout(1500)
        back_t = page.inner_text("body")
        check("return restores main", "path=" not in page.url
              and page.locator(".pm-path-bar").count() == 0 and back_t == main_t, page.url)

        def tamper(route):
            resp = route.fetch()
            route.fulfill(response=resp, body=resp.body() + b"\n")
        page.route("**/AutoGenerated/parameters.json", tamper)
        t = text(page, BASE + "parameters.html?path=" + PID)
        check("sha mismatch refused with notice", "results unavailable" in t)
        page.unroute("**/AutoGenerated/parameters.json")
        check("console errors", not errs, "; ".join(sorted(set(errs)))[:400])
        br.close()
finally:
    srv.terminate()
