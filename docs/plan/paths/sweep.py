"""Sequential per-path sweep: one `metaphysica.build --fast` per single-option
deviation, into RUNS/<fork>--<option>/. Resumable: skips a run whose DONE.json
records the current engine. A DONE.json from another engine state is rerun
(reusing runs_g after an engine fix published stale path diffs, 2026-10-26).
Sequential because the engine's AutoGenerated junction is shared."""
import hashlib, json, os, subprocess, sys, time
from pathlib import Path

from metaphysica.simulations.core import variants as v

RUNS = Path(sys.argv[1])
only = set(sys.argv[2:])


def deviations():
    act = v.active_selection()
    for f in v.FORKS.values():
        for o in f.options:
            if o.id != act[f.id]:
                yield f.id, o.id


def engine_id():
    """Engine HEAD plus a hash of its uncommitted diff."""
    repo = Path(v.__file__).resolve().parent
    git = lambda *a: subprocess.run(["git", "-C", str(repo), *a], check=True,
                                    capture_output=True).stdout
    head = git("rev-parse", "HEAD").decode().strip()
    return "%s+%s" % (head, hashlib.sha256(git("diff", "HEAD")).hexdigest()[:16])


def is_current(done, engine):
    try:
        return json.loads(done.read_text(encoding="utf-8")).get("engine") == engine
    except (OSError, ValueError):
        return False


def run(fork, option, engine):
    pid = "%s--%s" % (fork, option)
    out = RUNS / pid
    done = out / "DONE.json"
    if is_current(done, engine) or (only and pid not in only):
        return
    env = dict(os.environ)
    env["METAPHYSICA_VARIANT_" + fork.upper()] = option
    t0 = time.time()
    with open(RUNS / (pid + ".log"), "w", encoding="utf-8") as log:
        rc = subprocess.call([sys.executable, "-m", "metaphysica.build",
                              "--out", str(out), "--fast", "--keep-going"],
                             stdout=log, stderr=subprocess.STDOUT, env=env)
    rec = {"path": pid, "fork": fork, "option": option, "exit": rc,
           "engine": engine,
           "secs": round(time.time() - t0)}
    out.mkdir(parents=True, exist_ok=True)
    done.write_text(json.dumps(rec), encoding="utf-8")
    with open(RUNS / "sweep.jsonl", "a", encoding="utf-8") as f:
        f.write(json.dumps(rec) + "\n")
    print(rec, flush=True)


if __name__ == "__main__":
    engine = engine_id()
    for fork, option in deviations():
        run(fork, option, engine)
    print("SWEEP DONE")
