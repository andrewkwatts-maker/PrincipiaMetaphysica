"""Sequential per-selection sweep (Track G1). Usage:
    python sweep_paths.py RUNS selections.json [selection_id ...]
selections.json is a JSON list of {fork: option} maps (partial maps are fine:
unnamed forks keep the adopted default). Each runs `metaphysica.build --fast`
with METAPHYSICA_SELECTION pointing at RUNS/<selection_id>/selection.json,
output into RUNS/<selection_id>/. Resumable by the same rule as sweep.py: a
DONE.json recording the current engine is skipped, any other is rerun.
Sequential because the engine's AutoGenerated junction is shared."""
import hashlib, json, os, subprocess, sys, time
from pathlib import Path

from metaphysica.simulations.core import variants as v

RUNS = Path(sys.argv[1])
SELECTIONS = Path(sys.argv[2])
only = set(sys.argv[3:])


def engine_id():
    """Engine HEAD plus a hash of its uncommitted diff (as sweep.py)."""
    repo = Path(v.__file__).resolve().parent
    git = lambda *a: subprocess.run(["git", "-C", str(repo), *a], check=True,
                                    capture_output=True).stdout
    head = git("rev-parse", "HEAD").decode().strip()
    return "%s+%s" % (head, hashlib.sha256(git("diff", "HEAD")).hexdigest()[:16])


def is_current(done, engine):
    try:
        return json.loads(done.read_text(encoding="utf-8")).get("engine") == engine
    except (OSError, ValueError):
        return False


def load_all():
    """Validated selections, each as its departures; incompatible ones refused."""
    out = []
    for i, sel in enumerate(json.loads(SELECTIONS.read_text(encoding="utf-8"))):
        dep = v.departures(sel)           # unknown fork/option fails here
        bad = v.violations({**v.active_selection(), **dep})
        if bad:
            raise SystemExit("selection #%d is incompatible: %s" % (i, bad))
        out.append(dep)
    return out


def run(dep, engine):
    sid = v.selection_id(dep)
    out = RUNS / sid
    done = out / "DONE.json"
    if is_current(done, engine) or (only and sid not in only):
        return
    out.mkdir(parents=True, exist_ok=True)
    selfile = out / "selection.json"
    selfile.write_text(json.dumps(dep, sort_keys=True), encoding="utf-8")
    env = dict(os.environ)
    env["METAPHYSICA_SELECTION"] = str(selfile)
    t0 = time.time()
    with open(RUNS / (sid + ".log"), "w", encoding="utf-8") as log:
        rc = subprocess.call([sys.executable, "-m", "metaphysica.build",
                              "--out", str(out), "--fast", "--keep-going"],
                             stdout=log, stderr=subprocess.STDOUT, env=env)
    rec = {"path": sid, "selection": dep, "exit": rc, "engine": engine,
           "secs": round(time.time() - t0)}
    done.write_text(json.dumps(rec), encoding="utf-8")
    with open(RUNS / "sweep.jsonl", "a", encoding="utf-8") as f:
        f.write(json.dumps(rec) + "\n")
    print(rec, flush=True)


if __name__ == "__main__":
    RUNS.mkdir(parents=True, exist_ok=True)
    engine = engine_id()
    for dep in load_all():
        run(dep, engine)
    print("SWEEP DONE")
