import json,glob,os,collections,sys
os.chdir(sys.argv[1])
groups=collections.defaultdict(list)
for d in sorted(glob.glob('*--*')):
    if not os.path.isdir(d): continue
    bs=os.path.join(d,'AutoGenerated','build_status.json')
    if not os.path.exists(bs): groups['(no status: pre-E3 run)'].append(d); continue
    fs=json.load(open(bs,encoding='utf-8'))['failed_steps']
    sim=[s for s in fs if s['id']=='run_all_simulations']
    if sim: key='SIMS: '+(sim[0]['reason'] or 'null')[:110]
    elif fs: key='computed; failed: '+','.join(sorted(s['id'] for s in fs))[:200]
    else: key='computed; clean'
    groups[key].append(d)
for k,v in groups.items(): print(f'[{len(v)}] {k}\n    '+' '.join(v))
